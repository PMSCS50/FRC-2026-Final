package frc.robot.util.pathfinding.builders;

import java.util.List;
import java.util.function.Consumer;
import java.util.function.UnaryOperator;

import com.pathplanner.lib.commands.PathPlannerAuto;
import com.pathplanner.lib.path.PathConstraints;
import com.pathplanner.lib.path.PathPlannerPath;

import edu.wpi.first.math.geometry.Pose2d;
import frc.robot.util.Elastic;

// *An alternate way of creating pathfinder commands.
// ?Run PathRequest with Pathmaster.submitRequest()
// ?Best used for more complex pathfinding operations

public class PathRequest {
    private Pose2d targetPose;

    private PathPlannerPath targetPath;
    private boolean pathFindThenFollowPath;

    private List<Pose2d> stops = List.of();
    private PathConstraints constraints = null;
    private double goalEndVel = 0.0;
    private String[] activeZones = new String[0];

    private boolean auto = false;

    private UnaryOperator<PathPlannerAuto> eventTriggerFunction = (auto) -> auto;

    public PathRequest withGoal(Pose2d targetPose) {
        this.targetPose = targetPose;
        pathFindThenFollowPath = false;
        return this;
    }

    public PathRequest withGoal(PathPlannerPath targetPath) {
        this.targetPath = targetPath;
        pathFindThenFollowPath = true;
        return this;
    }

    public PathRequest withGoal(String targetPath) {
        try {
            if (targetPath.startsWith("choreo/")) {
                this.targetPath = PathPlannerPath.fromChoreoTrajectory(targetPath.substring(7));
            } else {
                this.targetPath = PathPlannerPath.fromPathFile(targetPath);
            }
        }
        catch (Exception e) {
            Elastic.sendNotification(
                new Elastic.Notification().
                withLevel(Elastic.NotificationLevel.ERROR)
                .withTitle("Pathmaster Error")
                .withDescription( "Path " + targetPath + " is not defined"));
        }
        finally {
            pathFindThenFollowPath = true;
        }
        return this;
    }

    public PathRequest withStops(List<Pose2d> stops) {
        this.stops = stops;
        return this;
    }

    public PathRequest withConstraints(PathConstraints constraints) {
        this.constraints = constraints;
        return this;
    }

    public PathRequest withGoalEndVelocity(double goalEndVel) {
        this.goalEndVel = goalEndVel;
        return this;
    }

    public PathRequest withActiveZones(String... activeZones) {
        this.activeZones = activeZones;
        return this;
    }

    public PathRequest runAsAuto(boolean auto) {
        this.auto = auto;
        return this;
    }

    public PathRequest withEventTriggers(UnaryOperator<PathPlannerAuto> eventTriggerFunction) {
        this.auto = true;
        this.eventTriggerFunction = eventTriggerFunction;
        return this;
    }

    //Just in case you forget to add "return auto;" to your lambda
    public PathRequest withEventTriggers(Consumer<PathPlannerAuto> eventTriggerConsumer) {
        this.auto = true;
        this.eventTriggerFunction = (auto) -> {
            eventTriggerConsumer.accept(auto);
            return auto;
        };
        return this;
    }

    // *Getters

    public Pose2d getTargetPose() {
        return targetPose;
    }

    public PathPlannerPath getTargetPath() {
        return targetPath;
    }

    public boolean isPathFindThenFollowPath() {
        return pathFindThenFollowPath;
    }

    public List<Pose2d> getStops() {
        return stops;
    }

    public PathConstraints getConstraints() {
        return constraints;
    }

    public double getGoalEndVel() {
        return goalEndVel;
    }

    public String[] getActiveZones() {
        return activeZones;
    }

    public boolean runsAsAuto() {
        return auto;
    }

    public UnaryOperator<PathPlannerAuto> EventTriggerFunction() {
        return eventTriggerFunction;
    }
}

